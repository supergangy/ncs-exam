# 「~법」 「~법령」 으로 끝나면 직무시험(법률)로 본다.
LAW_SUFFIX = ("법", "법령", "법률", "규정", "정관")


def section_kind(name: str) -> str:
    """키워드 절의 제목을 받아 ncs / major / law / 기타 로 가른다."""
    s = "".join(str(name).split())
    if any(a in s for a in NCS_AREAS) or s in {"의통", "문해", "의수문"}:
        return "ncs"
    if s.endswith(LAW_SUFFIX):
        return "law"
    for major, words in MAJOR_ALIASES.items():
        if any(w in s for w in words):
            return "major"
    return "기타"


def major_of(name: str) -> str | None:
    """전공 계열 이름으로 접는다. 「전기이론」·「전기직」 → 전기."""
    s = "".join(str(name or "").split())
    for major, words in MAJOR_ALIASES.items():
        if any(w in s for w in words):
            return major
    return None


