# 전산직은 과목 자체가 좁아 세부 유형이 그대로 대유형 노릇을 한다.
# 62종 / 150문항이고 표기가 갈린 것이 없어 묶지 않는다.
CS_SUBJECTS = frozenset({
    "네트워크", "데이터베이스론", "데이터통신", "소프트웨어공학",
    "운영체제", "전자계산기구조", "정보보안", "프로그래밍언어",
})


def _build() -> dict[tuple[str, str], str]:
    """(과목, 세부유형) → 대유형. 한 세부가 두 대유형에 들어가면 여기서 걸린다."""
    out: dict[tuple[str, str], str] = {}
    for (sj, group), members in GROUPS.items():
        for m in members:
            key = (sj, m)
            if key in out and out[key] != group:
                raise RuntimeError(
                    f"[유형 사전 충돌] {sj}/{m} 이 「{out[key]}」와 「{group}」 양쪽에 있다"
                )
            out[key] = group
    return out


TYPE_GROUP = _build()


def group_of(subject: str, type_: str) -> str:
    """대유형을 돌려준다. 전산직은 세부가 곧 대유형이다.

    사전에 없으면 **던진다.** 조용히 세부 이름을 그대로 쓰면 오늘의 오타가
    내일의 새 유형이 된다 — 표기가 갈린 그 경로다.
    """
    if subject in CS_SUBJECTS:
        return type_
    g = TYPE_GROUP.get((subject, type_))
    if g is None:
        raise KeyError(
            f"유형 사전에 없다: {subject}/{type_}\n"
            f"  → 오타인지 먼저 보고, 정말 새 유형이면 bank/qtypes.py 의 GROUPS 에 넣으십시오."
        )
    return g


def known(subject: str, type_: str) -> bool:
    return subject in CS_SUBJECTS or (subject, type_) in TYPE_GROUP
