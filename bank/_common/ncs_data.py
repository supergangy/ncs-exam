def _tbl(head, *rows, caption=None):
    cap = f"<caption>{caption}</caption>" if caption else ""
    h = "".join(f"<th>{c}</th>" for c in head)
    b = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f'<table class="data">{cap}<tr>{h}</tr>{b}</table>'


def _note(*lines):
    """각주. 여기 단위와 정의가 들어간다 — 안 읽으면 틀리게 만드는 자리다."""
    return "".join(f'<p class="note">{l}</p>' for l in lines)


def _bars(title, pairs, wrong=None):
    """막대그래프 SVG. 표를 그래프로 옳게 옮겼는지 묻는 문항에 쓴다.

    색으로 구분하지 않고(PLAYBOOK 8-12), <text> 는 11pt 이상(8-13),
    width 는 640 이하(8-11a).
    """
    vals = dict(pairs)
    if wrong:
        vals.update(wrong)
    top = max(vals.values())
    W, H, pad = 300, 150, 26
    bw = (W - pad * 2) / len(vals) - 10
    out = [f'<svg width="{W}" height="{H}" viewBox="0 0 {W} {H}" '
           f'xmlns="http://www.w3.org/2000/svg">']
    out.append(f'<text x="{W/2}" y="14" font-size="11" text-anchor="middle">{title}</text>')
    out.append(f'<line x1="{pad}" y1="{H-20}" x2="{W-pad+4}" y2="{H-20}" '
               f'stroke="#333" stroke-width="1"/>')
    for i, (k, v) in enumerate(vals.items()):
        h = (v / top) * (H - 56)
        x = pad + i * (bw + 10)
        out.append(f'<rect x="{x:.0f}" y="{H-20-h:.0f}" width="{bw:.0f}" height="{h:.0f}" '
                   f'fill="none" stroke="#333" stroke-width="1.2"/>')
        out.append(f'<text x="{x+bw/2:.0f}" y="{H-7}" font-size="11" '
                   f'text-anchor="middle">{k}</text>')
        out.append(f'<text x="{x+bw/2:.0f}" y="{H-24-h:.0f}" font-size="11" '
                   f'text-anchor="middle">{v}</text>')
    out.append("</svg>")
    return "".join(out)


