def _box(title, *lines):
    return ('<div class="box"><div class="box-title">&lt;' + title + '&gt;</div>'
            + "".join(f"<p>{l}</p>" for l in lines) + "</div>")


def _tbl(head, *rows):
    h = "".join(f"<th>{c}</th>" for c in head)
    b = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f'<table class="data"><tr>{h}</tr>{b}</table>'


